/**
 * Render standard duration cue mark:
 * - 192 ticks (whole): double open ring
 * - 144 ticks (dotted half): open ring + augmentation dot
 * - 96 ticks (half): single open ring
 * - 48 ticks (quarter): plain vertical stem tick
 * - 24 ticks (eighth): stem tick + flag notch
 */
export function renderHandprintDurationCue(
  x: number,
  y: number,
  durationTicks: number,
  scale: number = 1.0
): string {
  const r = 1.35 * scale;
  const dotR = 0.9 * scale;
  const strokeWidth = 0.65 * scale;
  const parts: string[] = [];

  if (durationTicks >= 192) {
    // Double open ring (whole note)
    parts.push(
      `<circle class="janko-handprint-dur-ring" cx="${f(x)}" cy="${f(y - r - 0.4)}" r="${f(r)}" fill="#FFFFFF" stroke="#111111" stroke-width="${f(strokeWidth)}"/>`
    );
    parts.push(
      `<circle class="janko-handprint-dur-ring" cx="${f(x)}" cy="${f(y + r + 0.4)}" r="${f(r)}" fill="#FFFFFF" stroke="#111111" stroke-width="${f(strokeWidth)}"/>`
    );
  } else if (durationTicks === 144) {
    // Single open ring + augmentation dot (dotted half)
    parts.push(
      `<circle class="janko-handprint-dur-ring" cx="${f(x)}" cy="${f(y)}" r="${f(r)}" fill="#FFFFFF" stroke="#111111" stroke-width="${f(strokeWidth)}"/>`
    );
    parts.push(
      `<circle class="janko-handprint-dur-dot" cx="${f(x + r + dotR + 1.2)}" cy="${f(y)}" r="${f(dotR)}" fill="#111111"/>`
    );
  } else if (durationTicks >= 96) {
    // Single open ring (half note)
    parts.push(
      `<circle class="janko-handprint-dur-ring" cx="${f(x)}" cy="${f(y)}" r="${f(r)}" fill="#FFFFFF" stroke="#111111" stroke-width="${f(strokeWidth)}"/>`
    );
  } else if (durationTicks >= 48) {
    // Plain quarter stem tick
    parts.push(
      `<line class="janko-handprint-dur-stem" x1="${f(x)}" y1="${f(y - 3.5 * scale)}" x2="${f(x)}" y2="${f(y + 3.5 * scale)}" stroke="#111111" stroke-width="${f(0.85 * scale)}"/>`
    );
  } else if (durationTicks >= 24) {
    // Eighth note stem tick + flag
    parts.push(
      `<line class="janko-handprint-dur-stem" x1="${f(x)}" y1="${f(y - 3.5 * scale)}" x2="${f(x)}" y2="${f(y + 3.5 * scale)}" stroke="#111111" stroke-width="${f(0.85 * scale)}"/>`
    );
    parts.push(
      `<line class="janko-handprint-dur-flag" x1="${f(x)}" y1="${f(y - 2.5 * scale)}" x2="${f(x + 2.5 * scale)}" y2="${f(y - 0.8 * scale)}" stroke="#111111" stroke-width="${f(0.75 * scale)}"/>`
    );
  } else {
    // 16th note stem tick + double flag
    parts.push(
      `<line class="janko-handprint-dur-stem" x1="${f(x)}" y1="${f(y - 3.5 * scale)}" x2="${f(x)}" y2="${f(y + 3.5 * scale)}" stroke="#111111" stroke-width="${f(0.85 * scale)}"/>`
    );
    parts.push(
      `<line class="janko-handprint-dur-flag" x1="${f(x)}" y1="${f(y - 2.8 * scale)}" x2="${f(x + 2.5 * scale)}" y2="${f(y - 1.2 * scale)}" stroke="#111111" stroke-width="${f(0.75 * scale)}"/>`
    );
    parts.push(
      `<line class="janko-handprint-dur-flag" x1="${f(x)}" y1="${f(y - 1.2 * scale)}" x2="${f(x + 2.5 * scale)}" y2="${f(y + 0.4 * scale)}" stroke="#111111" stroke-width="${f(0.75 * scale)}"/>`
    );
  }

  return parts.join('');
}

