/**
 * Mirrored Handprint — Whole-Form Cluster Element Module (Round 36 Candidate)
 * ===========================================================================
 *
 * A rotated keyboard footprint supplies glyph-local geometry for dense hand
 * clusters (4- and 5-note groups at the same onset and hand); surrounding
 * fixed-3 staff is unchanged.
 *
 * Geometry:
 * - Anchor is the lowest sounding pitch p0, with explicit absolute solf numeral
 *   and register placement coinciding with the anchor's displayed staff height.
 * - Local y[i] = -u * (p[i] - p0), increasing pitch upward (u = 2.4 pt/semitone).
 * - Local x[i] = +a for odd p[i], -a for even p[i] (a = 3.0 pt).
 * - Central axis is the onset axis.
 * - Odd-semitone transposition reflects internal form left/right;
 *   even-semitone transposition preserves it, generated by ONE mirrored geometry routine.
 * - Landmarks connected in ascending order as a single narrow, smoothly joined
 *   calligraphic body with small outward shoulders/lobes at sounding landmarks.
 * - Base numeral integrated at the origin; other numerals absent.
 * - Clearly owned duration attachments: uniform rhythm shared at summit;
 *   differing releases visibly attached to relevant landmark shoulders.
 * - Exact inverse pitch decoding recoverable from anchor + landmark geometry.
 */

