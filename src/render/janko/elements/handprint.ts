/** Get sounding linear pitch from a note or positioned note. */
export function getSoundingPitch(note: QuantizedNote | PositionedJankoNote): number {
  const q = 'note' in note ? note.note : note;
  const pc = ((q.pitch.pitchClass % 12) + 12) % 12;
  return q.pitch.octave * 12 + pc;
}

/**
 * Group positioned notes into handprint clusters.
 * Focus: same-hand, same-onset 4- and 5-note groups (>= 4 notes).
 * 2/3-note groups stay literal for this experiment.
 */
export function groupHandprintClusters(
  notes: readonly PositionedJankoNote[],
  u: number = HANDPRINT_PITCH_UNIT_U,
  a: number = HANDPRINT_ROW_DISPLACEMENT_A
): {
  clusters: JankoHandprintCluster[];
  handprintNoteIds: Set<string>;
} {
  // Group notes by startTick and hand
  const byOnset = new Map<string, PositionedJankoNote[]>();
  for (const n of notes) {
    const k = `${n.note.startTick}_${n.note.hand}`;
    const list = byOnset.get(k);
    if (list) {
      list.push(n);
    } else {
      byOnset.set(k, [n]);
    }
  }

  const clusters: JankoHandprintCluster[] = [];
  const handprintNoteIds = new Set<string>();

  for (const group of byOnset.values()) {
    if (group.length < 4) continue; // 2/3-note groups stay literal

    // Sort constituent notes strictly ascending by sounding linear pitch
    const sorted = [...group].sort((n1, n2) => getSoundingPitch(n1) - getSoundingPitch(n2));
    const anchorNote = sorted[0];
    const baseLin = getSoundingPitch(anchorNote);
    const basePitchClass = ((baseLin % 12) + 12) % 12;
    const anchorStaffY = anchorNote.y;

    // The onset axis is the nominal unshifted column X of the onset
    // In Janko layout, anchorNote.x sits on the onset column
    const onsetX = Math.min(...group.map((n) => n.x));

    const landmarks: JankoHandprintLandmark[] = sorted.map((n) => {
      const pitch = getSoundingPitch(n);
      const pc = ((pitch % 12) + 12) % 12;
      const parity: 0 | 1 = (pitch % 2 !== 0) ? 1 : 0;
      const localX = parity === 1 ? +a : -a;
      const localY = -u * (pitch - baseLin);
      return {
        pitch,
        pitchClass: pc,
        parity,
        localX,
        localY,
        x: onsetX + localX,
        y: anchorStaffY + localY,
        durationTicks: n.note.durationTicks,
        noteId: n.note.id,
      };
    });

    // Partition by duration ticks
    const durMap = new Map<number, JankoHandprintLandmark[]>();
    for (const lm of landmarks) {
      const list = durMap.get(lm.durationTicks);
      if (list) list.push(lm);
      else durMap.set(lm.durationTicks, [lm]);
    }

    const isUniformRhythm = durMap.size === 1;
    const uniformDurationTicks = isUniformRhythm ? landmarks[0].durationTicks : undefined;

    const durationSubsets: JankoHandprintDurationSubset[] = [];
    for (const [dur, lms] of durMap.entries()) {
      // Owned attachment site: the highest landmark in this duration subset
      const highestLm = lms[lms.length - 1];
      durationSubsets.push({
        durationTicks: dur,
        noteIds: lms.map((l) => l.noteId),
        landmark: highestLm,
      });
    }

    // Sort duration subsets ascending by duration
    durationSubsets.sort((a, b) => a.durationTicks - b.durationTicks);

    // Compute ink bounding box
    let minX = onsetX - a - HANDPRINT_LOBE_WIDTH;
    let maxX = onsetX + a + HANDPRINT_LOBE_WIDTH;
    let minY = landmarks[landmarks.length - 1].y - HANDPRINT_LOBE_HALF_HEIGHT;
    let maxY = anchorStaffY + HANDPRINT_LOBE_HALF_HEIGHT;

    // Account for origin knockout/digit
    minX = Math.min(minX, onsetX - a - HANDPRINT_ORIGIN_KNOCKOUT_WX);
    maxX = Math.max(maxX, onsetX + a + HANDPRINT_ORIGIN_KNOCKOUT_WX);
    minY = Math.min(minY, anchorStaffY - HANDPRINT_ORIGIN_KNOCKOUT_HY);
    maxY = Math.max(maxY, anchorStaffY + HANDPRINT_ORIGIN_KNOCKOUT_HY);

    // Account for duration attachments (approx 6pt outward or 8pt upward)
    if (isUniformRhythm) {
      minY -= 9.0; // Summit duration cue extends upward
    } else {
      maxX += 8.0; // Differing release cues extend outward
      minX -= 4.0;
    }

    const cluster: JankoHandprintCluster = {
      id: `handprint-${anchorNote.note.startTick}-${anchorNote.note.hand}`,
      startTick: anchorNote.note.startTick,
      hand: anchorNote.note.hand,
      baseLin,
      basePitchClass,
      anchorStaffY,
      onsetX,
      landmarks,
      allNoteIds: new Set(group.map((n) => n.note.id)),
      notes: sorted,
      inkBox: [minX, minY, maxX, maxY],
      durationSubsets,
      isUniformRhythm,
      uniformDurationTicks,
    };

    clusters.push(cluster);
    for (const n of group) {
      handprintNoteIds.add(n.note.id);
    }
  }

  return { clusters, handprintNoteIds };
}

