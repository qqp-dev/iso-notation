/** Sounding landmark of one constituent pitch in a handprint cluster. */
export interface JankoHandprintLandmark {
  /** Sounding linear pitch: 12 * octave + pitchClass. */
  pitch: number;
  /** Pitch class (0..11). */
  pitchClass: number;
  /** Parity: 0 for even, 1 for odd. */
  parity: 0 | 1;
  /** Local horizontal offset from onset axis (pt): +a for odd, -a for even. */
  localX: number;
  /** Local vertical offset from anchor staff height (pt): -u * (pitch - p0). */
  localY: number;
  /** Page absolute X (pt): onsetX + localX. */
  x: number;
  /** Page absolute Y (pt): anchorStaffY + localY. */
  y: number;
  /** Duration (ticks) of this constituent note. */
  durationTicks: number;
  /** Source note ID. */
  noteId: string;
}

/** Distinct duration release subset within a handprint cluster. */
export interface JankoHandprintDurationSubset {
  durationTicks: number;
  noteIds: string[];
  /** Landmark this duration attachment owns and attaches to. */
  landmark: JankoHandprintLandmark;
}

/** Intrinsic scale reference division in an indexed symmetric cluster form. */
export interface JankoHandprintScaleDivision {
  /** Offset in semitones from anchor (0, 2, 4, ...). */
  offset: number;
  /** Page absolute Y coordinate (pt). */
  y: number;
  /** True if offset > 0 and offset is a multiple of 12 semitones (duodecimal 10-span). */
  isOctave: boolean;
  /** Transverse line width in pt. */
  width: number;
  /** Stroke width in pt. */
  strokeWidth: number;
}

/** Contiguous run of landmarks sharing the exact same duration. */
export interface JankoHandprintDurationRun {
  durationTicks: number;
  noteIds: string[];
  landmarks: JankoHandprintLandmark[];
}

/** One candidate handprint cluster representing a dense 4/5-note chord. */
export interface JankoHandprintCluster {
  id: string;
  startTick: number;
  hand: Hand;
  /** Sounding linear pitch of the anchor (lowest note). */
  baseLin: number;
  /** Anchor pitch class (0..11). */
  basePitchClass: number;
  /** Displayed staff height of the anchor note (page pt). */
  anchorStaffY: number;
  /** Central onset axis column on page (pt). */
  onsetX: number;
  /** Sounding landmarks in ascending pitch order. */
  landmarks: JankoHandprintLandmark[];
  /** Set of all source note IDs in this cluster. */
  allNoteIds: Set<string>;
  /** Positioned notes belonging to this cluster. */
  notes: PositionedJankoNote[];
  /** Bounding box of all ink: [minX, minY, maxX, maxY] in page pt. */
  inkBox: [number, number, number, number];
  /** Distinct duration release subsets. */
  durationSubsets: JankoHandprintDurationSubset[];
  /** True if all constituent notes share the exact same duration. */
  isUniformRhythm: boolean;
  /** The uniform duration in ticks (if uniform). */
  uniformDurationTicks?: number;
  /** Active cluster presentation candidate. */
  presentation?: JankoClusterPresentation;
  /** True when anchor is shared with LH unison bass note (m.60). */
  hasSharedAnchor?: boolean;
  /** Note ID of the surviving shared bass anchor note (e.g. LH survivor in m.60). */
  sharedBassSurvivorId?: string;
  /** Transverse reference divisions (Round 37). */
  scaleDivisions?: JankoHandprintScaleDivision[];
  /** Contiguous duration runs for explicit visible ownership (Round 37). */
  durationRuns?: JankoHandprintDurationRun[];
}

