/**
 * Render the complete mirrored handprint SVG group for one cluster:
 * 1. Connected calligraphic body `<path class="janko-handprint-body" ...>`
 * 2. Origin base numeral with white knockout and duodecimal digit
 * 3. Clearly owned duration attachments
 */
export function renderHandprintSvg(
  cluster: JankoHandprintCluster,
  tokens: ResolvedJankoTokens
): { svg: string; inkBox: [number, number, number, number] } {
  const parts: string[] = [];
  parts.push(`  <g class="janko-mirrored-handprint" data-cluster-id="${cluster.id}">`);

  // 1. Single connected calligraphic body path
  const bodyPathD = renderHandprintBodyPath(cluster.landmarks);
  parts.push(
    `    <path class="janko-handprint-body" d="${bodyPathD}" fill="#111111" stroke="none"/>`
  );

  // 2. Base numeral integrated at the origin (landmark 0)
  const originLm = cluster.landmarks[0];
  const digit = getDuodecimalDigit(cluster.basePitchClass);
  const baseline = originLm.y + digitBaselineOffset(tokens.digitFontSize);
  const kwx = HANDPRINT_ORIGIN_KNOCKOUT_WX;
  const khy = HANDPRINT_ORIGIN_KNOCKOUT_HY;

  // White knockout behind the base digit
  parts.push(
    `    <rect class="janko-knockout" x="${f(originLm.x - kwx)}" y="${f(originLm.y - khy)}" width="${f(2 * kwx)}" height="${f(2 * khy)}" fill="#FFFFFF"/>`
  );
  // Upright, readable duodecimal digit (never mirrored)
  parts.push(
    `    <text class="janko-digit" x="${f(originLm.x)}" y="${f(baseline)}" font-weight="700" font-size="${tokens.digitFontSize.toFixed(1)}pt" fill="#111111">${digit}</text>`
  );

  // 3. Clearly owned duration attachments
  if (cluster.isUniformRhythm && cluster.uniformDurationTicks !== undefined) {
    // Uniform rhythm: shared attachment site at the summit of the glyph
    const topLm = cluster.landmarks[cluster.landmarks.length - 1];
    const stemY = topLm.y - HANDPRINT_LOBE_HALF_HEIGHT - 3.5;
    // Connector line from summit up to duration cue
    parts.push(
      `    <line class="janko-handprint-dur-connector" x1="${f(topLm.x)}" y1="${f(topLm.y - HANDPRINT_LOBE_HALF_HEIGHT)}" x2="${f(topLm.x)}" y2="${f(stemY + 2.0)}" stroke="#111111" stroke-width="0.75"/>`
    );
    parts.push(`    ${renderHandprintDurationCue(topLm.x, stemY, cluster.uniformDurationTicks)}`);
  } else {
    // Differing releases: visibly attached to relevant landmark shoulders
    for (const subset of cluster.durationSubsets) {
      const lm = subset.landmark;
      const isOdd = lm.parity === 1;
      const sign = isOdd ? 1 : -1;
      const attachX = lm.x + sign * (HANDPRINT_LOBE_WIDTH + 1.2);
      const cueX = attachX + sign * 2.2;
      const cueY = lm.y;

      // Small horizontal attachment line from landmark shoulder to cue
      parts.push(
        `    <line class="janko-handprint-dur-connector" x1="${f(lm.x + sign * HANDPRINT_LOBE_WIDTH)}" y1="${f(cueY)}" x2="${f(attachX)}" y2="${f(cueY)}" stroke="#111111" stroke-width="0.75"/>`
      );
      parts.push(`    ${renderHandprintDurationCue(cueX, cueY, subset.durationTicks, 0.9)}`);
    }
  }

  parts.push('  </g>');
  return {
    svg: parts.join('\n'),
    inkBox: cluster.inkBox,
  };
}

