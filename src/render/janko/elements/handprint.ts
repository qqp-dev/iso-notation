/**
 * Decode linear pitches from anchor pitch, displayed staff height, onset X,
 * and landmark coordinates.
 *
 * Demonstrates inverse pitch recovery strictly from geometric landmarks,
 * NOT by returning a hidden saved source-note array.
 */
export function decodeHandprintLandmarks(
  baseLin: number,
  anchorStaffY: number,
  onsetX: number,
  landmarks: readonly { x: number; y: number }[],
  u: number = HANDPRINT_PITCH_UNIT_U,
  a: number = HANDPRINT_ROW_DISPLACEMENT_A
): number[] {
  void a;
  return landmarks.map((lm) => {
    const deltaY = lm.y - anchorStaffY;
    const semitonesFromBase = Math.round(-deltaY / u);
    const recoveredPitch = baseLin + semitonesFromBase;

    // Verify parity agreement from horizontal position
    const deltaX = lm.x - onsetX;
    const expectedParity = deltaX > 0 ? 1 : 0;
    const actualParity = (recoveredPitch % 2 !== 0) ? 1 : 0;
    if (expectedParity !== actualParity) {
      throw new Error(
        `Parity mismatch during decoding: landmark at x=${lm.x.toFixed(2)} (deltaX=${deltaX.toFixed(2)}) ` +
        `implies parity ${expectedParity}, but recovered pitch ${recoveredPitch} has parity ${actualParity}`
      );
    }

    return recoveredPitch;
  });
}

/**
 * Return discrete bounding boxes for all ink primitives that make up a handprint cluster:
 * - Origin knockout and base numeral box
 * - Sounding landmark lobes
 * - Connecting calligraphic body segments
 * - Duration attachment cues and connectors
 */
export function getHandprintPrimitives(
  cluster: JankoHandprintCluster
): Array<[number, number, number, number]> {
  const boxes: Array<[number, number, number, number]> = [];
  const lms = cluster.landmarks;
  if (lms.length === 0) return boxes;

  // 1. Origin knockout / digit box
  const origin = lms[0];
  boxes.push([
    origin.x - HANDPRINT_ORIGIN_KNOCKOUT_WX,
    origin.y - HANDPRINT_ORIGIN_KNOCKOUT_HY,
    origin.x + HANDPRINT_ORIGIN_KNOCKOUT_WX,
    origin.y + HANDPRINT_ORIGIN_KNOCKOUT_HY,
  ]);

  // 2. Landmark lobes
  for (const lm of lms) {
    if (lm.parity === 1) {
      boxes.push([
        lm.x - HANDPRINT_BODY_HALF_WIDTH,
        lm.y - HANDPRINT_LOBE_HALF_HEIGHT,
        lm.x + HANDPRINT_LOBE_WIDTH,
        lm.y + HANDPRINT_LOBE_HALF_HEIGHT,
      ]);
    } else {
      boxes.push([
        lm.x - HANDPRINT_LOBE_WIDTH,
        lm.y - HANDPRINT_LOBE_HALF_HEIGHT,
        lm.x + HANDPRINT_BODY_HALF_WIDTH,
        lm.y + HANDPRINT_LOBE_HALF_HEIGHT,
      ]);
    }
  }

  // 3. Connecting segments
  for (let i = 0; i < lms.length - 1; i++) {
    const yTop = lms[i + 1].y;
    const yBot = lms[i].y;
    const minX = Math.min(lms[i].x, lms[i + 1].x) - HANDPRINT_BODY_HALF_WIDTH;
    const maxX = Math.max(lms[i].x, lms[i + 1].x) + HANDPRINT_BODY_HALF_WIDTH;
    boxes.push([minX, yTop, maxX, yBot]);
  }

  // 4. Duration attachments
  if (cluster.isUniformRhythm && cluster.uniformDurationTicks !== undefined) {
    const topLm = lms[lms.length - 1];
    const stemY = topLm.y - HANDPRINT_LOBE_HALF_HEIGHT - 3.5;
    boxes.push([topLm.x - 3.5, stemY - 4.5, topLm.x + 3.5, topLm.y]);
  } else {
    for (const subset of cluster.durationSubsets) {
      const lm = subset.landmark;
      if (lm.parity === 1) {
        boxes.push([
          lm.x + HANDPRINT_LOBE_WIDTH,
          lm.y - 3.5,
          lm.x + HANDPRINT_LOBE_WIDTH + 8.5,
          lm.y + 3.5,
        ]);
      } else {
        boxes.push([
          lm.x - HANDPRINT_LOBE_WIDTH - 8.5,
          lm.y - 3.5,
          lm.x - HANDPRINT_LOBE_WIDTH,
          lm.y + 3.5,
        ]);
      }
    }
  }

  return boxes;
}

function boxIntersectsBox(
  b1: readonly [number, number, number, number],
  b2: readonly [number, number, number, number],
  clearance: number
): boolean {
  return (
    b1[0] - clearance <= b2[2] &&
    b1[2] + clearance >= b2[0] &&
    b1[1] - clearance <= b2[3] &&
    b1[3] + clearance >= b2[1]
  );
}

