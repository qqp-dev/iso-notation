/**
 * Construct the SVG path data for the single narrow, smoothly joined calligraphic body.
 * Connects landmarks in ascending order with small outward shoulders/lobes at sounding landmarks.
 *
 * This routine is purely mirrored: odd transposition reflects x left/right;
 * even transposition preserves geometry identically.
 */
export function renderHandprintBodyPath(
  landmarks: readonly JankoHandprintLandmark[],
  wLobe: number = HANDPRINT_LOBE_WIDTH,
  hLobe: number = HANDPRINT_LOBE_HALF_HEIGHT,
  wBody: number = HANDPRINT_BODY_HALF_WIDTH
): string {
  if (landmarks.length === 0) return '';
  const n = landmarks.length;

  // Build right-side contour ascending from landmark 0 to n-1
  const rightPoints: Array<{ x: number; y: number; cmd?: string; cp1?: { x: number; y: number }; cp2?: { x: number; y: number } }> = [];

  for (let i = 0; i < n; i++) {
    const lm = landmarks[i];
    const isOdd = lm.parity === 1;

    if (isOdd) {
      // Landmark is on right (+a). Outward shoulder/lobe swells outward to the right (+x)
      const xBase = lm.x + wBody;
      const xApex = lm.x + wLobe;
      const yBot = lm.y + hLobe;
      const yMid = lm.y;
      const yTop = lm.y - hLobe;

      // Start of lobe, curve to apex, curve back to body
      rightPoints.push({ x: xBase, y: yBot, cmd: 'L' });
      rightPoints.push({
        x: xApex,
        y: yMid,
        cmd: 'C',
        cp1: { x: xApex, y: yBot },
        cp2: { x: xApex, y: yMid + 0.3 * hLobe },
      });
      rightPoints.push({
        x: xBase,
        y: yTop,
        cmd: 'C',
        cp1: { x: xApex, y: yMid - 0.3 * hLobe },
        cp2: { x: xApex, y: yTop },
      });
    } else {
      // Landmark is on left (-a). Right side is the inward body boundary
      const xInward = lm.x + wBody;
      rightPoints.push({ x: xInward, y: lm.y, cmd: 'L' });
    }
  }

  // Summit transition: wrap over the top landmark (n - 1)
  const topLm = landmarks[n - 1];
  const summitOver = {
    x: topLm.x,
    y: topLm.y - hLobe - 0.5,
  };

  // Build left-side contour descending from landmark n-1 down to 0
  const leftPoints: Array<{ x: number; y: number; cmd?: string; cp1?: { x: number; y: number }; cp2?: { x: number; y: number } }> = [];

  for (let i = n - 1; i >= 0; i--) {
    const lm = landmarks[i];
    const isEven = lm.parity === 0;

    if (isEven) {
      // Landmark is on left (-a). Outward shoulder/lobe swells outward to the left (-x)
      const xBase = lm.x - wBody;
      const xApex = lm.x - wLobe;
      const yTop = lm.y - hLobe;
      const yMid = lm.y;
      const yBot = lm.y + hLobe;

      leftPoints.push({ x: xBase, y: yTop, cmd: 'L' });
      leftPoints.push({
        x: xApex,
        y: yMid,
        cmd: 'C',
        cp1: { x: xApex, y: yTop },
        cp2: { x: xApex, y: yMid - 0.3 * hLobe },
      });
      leftPoints.push({
        x: xBase,
        y: yBot,
        cmd: 'C',
        cp1: { x: xApex, y: yMid + 0.3 * hLobe },
        cp2: { x: xApex, y: yBot },
      });
    } else {
      // Landmark is on right (+a). Left side is the inward body boundary
      const xInward = lm.x - wBody;
      leftPoints.push({ x: xInward, y: lm.y, cmd: 'L' });
    }
  }

  // Base transition: wrap under the bottom landmark (0)
  const botLm = landmarks[0];
  const baseUnder = {
    x: botLm.x,
    y: botLm.y + hLobe + 0.5,
  };

  // Assemble the closed SVG path string
  const dParts: string[] = [];
  const start = rightPoints[0];
  dParts.push(`M ${f(start.x)} ${f(start.y)}`);

  for (let i = 1; i < rightPoints.length; i++) {
    const pt = rightPoints[i];
    if (pt.cmd === 'C' && pt.cp1 && pt.cp2) {
      dParts.push(`C ${f(pt.cp1.x)} ${f(pt.cp1.y)}, ${f(pt.cp2.x)} ${f(pt.cp2.y)}, ${f(pt.x)} ${f(pt.y)}`);
    } else {
      dParts.push(`L ${f(pt.x)} ${f(pt.y)}`);
    }
  }

  // Over summit
  dParts.push(`Q ${f(summitOver.x)} ${f(summitOver.y)}, ${f(leftPoints[0].x)} ${f(leftPoints[0].y)}`);

  for (let i = 1; i < leftPoints.length; i++) {
    const pt = leftPoints[i];
    if (pt.cmd === 'C' && pt.cp1 && pt.cp2) {
      dParts.push(`C ${f(pt.cp1.x)} ${f(pt.cp1.y)}, ${f(pt.cp2.x)} ${f(pt.cp2.y)}, ${f(pt.x)} ${f(pt.y)}`);
    } else {
      dParts.push(`L ${f(pt.x)} ${f(pt.y)}`);
    }
  }

  // Under base and close
  dParts.push(`Q ${f(baseUnder.x)} ${f(baseUnder.y)}, ${f(start.x)} ${f(start.y)}`);
  dParts.push('Z');

  return dParts.join(' ');
}

