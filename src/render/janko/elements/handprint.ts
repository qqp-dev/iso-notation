// Clearance Verification
// ---------------------------------------------------------------------------

/**
 * Check whether handprint cluster ink collides with barlines, noteheads, or rests.
 * Uses a broad-phase bounding-box test followed by a narrow-phase check against
 * actual ink primitives (origin knockout, landmark lobes, connecting segments,
 * and duration attachment cues).
 */
export function checkHandprintCollisions(
  cluster: JankoHandprintCluster,
  barlineXs: readonly number[],
  independentNotes: readonly PositionedJankoNote[],
  rests: readonly any[],
  minClearance: number = 1.0
): { collides: boolean; obstacle?: string; details?: string } {
  const [minX, minY, maxX, maxY] = cluster.inkBox;
  const primitives = getHandprintPrimitives(cluster);

  // 1. Check barlines
  for (const bx of barlineXs) {
    if (bx >= minX - minClearance && bx <= maxX + minClearance) {
      for (const prim of primitives) {
        if (bx >= prim[0] - minClearance && bx <= prim[2] + minClearance) {
          return {
            collides: true,
            obstacle: 'barline',
            details: `Cluster ink touches barline at x=${bx.toFixed(1)}`,
          };
        }
      }
    }
  }

  // 2. Check independent noteheads (other hand or different onset)
  for (const n of independentNotes) {
    const noteId = n.note?.id ?? (n as any).id;
    if (cluster.allNoteIds.has(noteId)) continue;
    const nx = n.x;
    const ny = n.y;
    if (nx === undefined || ny === undefined) continue;
    const wx = 2.53;
    const hy = 3.46;
    const noteBox: [number, number, number, number] = [nx - wx, ny - hy, nx + wx, ny + hy];

    // Broad phase
    if (!boxIntersectsBox(cluster.inkBox, noteBox, minClearance)) continue;

    // Narrow phase
    for (const prim of primitives) {
      if (boxIntersectsBox(prim, noteBox, minClearance)) {
        return {
          collides: true,
          obstacle: 'notehead',
          details: `Cluster ink touches notehead ${noteId} at (${nx.toFixed(1)}, ${ny.toFixed(1)})`,
        };
      }
    }
  }

  // 3. Check rests
  for (const r of rests) {
    if (r && typeof r.x === 'number' && typeof r.y === 'number') {
      const rx = r.x;
      const ry = r.y;
      const rw = 4.0;
      const rh = 6.0;
      const restBox: [number, number, number, number] = [rx - rw, ry - rh, rx + rw, ry + rh];

      // Broad phase
      if (!boxIntersectsBox(cluster.inkBox, restBox, minClearance)) continue;

      // Narrow phase
      for (const prim of primitives) {
        if (boxIntersectsBox(prim, restBox, minClearance)) {
          return {
            collides: true,
            obstacle: 'rest',
            details: `Cluster ink touches rest at (${rx.toFixed(1)}, ${ry.toFixed(1)})`,
          };
        }
      }
    }
  }

  return { collides: false };
}
